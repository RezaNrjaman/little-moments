import { z } from "zod";
import { isValid, parseISO } from "date-fns";
import {
  ALLOWED_IMAGE_TYPES,
  MAX_IMAGE_SIZE_BYTES,
  MAX_MEMORY_PHOTOS,
} from "@/config/site";
import type { MemoryFilter } from "@/features/memories/types";

/**
 * Validation schemas (Zod) shared by Server Actions, Route Handlers and
 * the React Hook Form client forms. The server never trusts browser input.
 */

const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;

/** YYYY-MM-DD and a real calendar day. */
const dateString = z
  .string()
  .trim()
  .regex(DATE_PATTERN, "Gunakan tanggal yang valid (YYYY-MM-DD).")
  .refine((value) => isValid(parseISO(value)), {
    message: "Gunakan tanggal kalender yang valid.",
  });

const uuid = z.string().uuid("ID tidak valid.");

const title = z
  .string()
  .trim()
  .min(1, "Tambahkan judul untuk kenangan ini.")
  .max(120, "Judul terlalu panjang (maks 120 karakter).");

const description = z
  .string()
  .trim()
  .max(5000, "Cerita terlalu panjang (maks 5000 karakter).");

const location = z
  .string()
  .trim()
  .max(200, "Lokasi terlalu panjang (maks 200 karakter).");

/** Storage path generated by /api/uploads/sign: uuid.<allowed ext>. */
const imagePath = z
  .string()
  .trim()
  .regex(
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp)$/i,
    "Referensi foto tidak valid.",
  );

const uploadTicket = z
  .string()
  .trim()
  .min(20, "Izin unggah tidak ditemukan.")
  .max(2048);

/** One uploaded photo: server authorised path + its upload ticket. */
export const memoryImageUploadSchema = z.object({
  imagePath,
  uploadTicket,
});

/** Form-facing schema (React Hook Form); photos are handled separately. */
export const memoryFormSchema = z.object({
  title,
  description,
  memoryDate: dateString,
  location,
});

export const createMemorySchema = memoryFormSchema.extend({
  images: z
    .array(memoryImageUploadSchema)
    .min(1, "Pilih minimal satu foto untuk kenangan ini.")
    .max(MAX_MEMORY_PHOTOS, `Maksimal ${MAX_MEMORY_PHOTOS} foto per kenangan.`),
});

export const updateMemorySchema = z.object({
  id: uuid,
  ...memoryFormSchema.shape,
  currentImagePath: z.string().trim().min(1),
  imagePath: imagePath.optional(),
  uploadTicket: uploadTicket.optional(),
  addedImages: z
    .array(memoryImageUploadSchema)
    .max(MAX_MEMORY_PHOTOS)
    .optional()
    .default([]),
  removedImageIds: z.array(uuid).max(MAX_MEMORY_PHOTOS).optional().default([]),
});

export const deleteMemorySchema = z.object({
  id: uuid,
});

export const loginSchema = z.object({
  password: z.string().min(1, "Kata sandi belum diisi.").max(256),
});

export const uploadSignSchema = z.object({
  contentType: z.enum(Object.keys(ALLOWED_IMAGE_TYPES) as [string, ...string[]]),
  size: z
    .number()
    .int()
    .positive()
    .max(MAX_IMAGE_SIZE_BYTES, "Foto terlalu besar (maks 5 MB)."),
});

/** Parse the ?view=...&date=... query into a typed filter (PRD FR-07). */
export function parseMemoryFilter(
  searchParams: Record<string, string | string[] | undefined>,
): { filter: MemoryFilter; error: string | null } {
  const single = (value: string | string[] | undefined): string | null =>
    typeof value === "string" ? value : null;

  const view = single(searchParams.view);

  if (!view || view === "all") {
    return { filter: identityFilter(), error: null };
  }

  if (view === "day") {
    const date = single(searchParams.date);
    if (date && DATE_PATTERN.test(date) && isValid(parseISO(date))) {
      return { filter: { view: "day", date }, error: null };
    }
    return { filter: identityFilter(), error: "Filter tanggal tidak valid." };
  }

  if (view === "month") {
    const month = single(searchParams.month);
    if (month && /^\d{4}-(0[1-9]|1[0-2])$/.test(month)) {
      return { filter: { view: "month", month }, error: null };
    }
    return {
      filter: identityFilter(),
      error: "Filter bulan tidak valid.",
    };
  }

  if (view === "year") {
    const year = single(searchParams.year);
    if (year && /^\d{4}$/.test(year)) {
      return { filter: { view: "year", year }, error: null };
    }
    return {
      filter: identityFilter(),
      error: "Filter tahun tidak valid.",
    };
  }

  return { filter: identityFilter(), error: "Filter tidak didukung." };
}

function identityFilter(): MemoryFilter {
  return { view: "all" };
}
